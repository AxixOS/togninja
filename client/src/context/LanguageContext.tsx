// English source strings — the admin "Generate translations" action sends these to
// the server for AI translation into French/Spanish.
export const enTranslations = translations.en as Record<string, string>;

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, _setLanguage] = useState<Language>(() => {
    // Prefer a user-chosen language only if the user has explicitly changed it before
    const savedLang = (() => {
      try { return localStorage.getItem('language'); } catch { return null; }
    })();
    const userSet = (() => {
      try { return localStorage.getItem('languageUserSet'); } catch { return null; }
    })();

    if (userSet === 'true' && savedLang && (SUPPORTED_LANGS as string[]).includes(savedLang)) {
      return savedLang as Language;
    }

    // Clean up any old cached English preference if user hasn't explicitly chosen
    try {
      if (savedLang === 'en' && userSet !== 'true') {
        localStorage.removeItem('language');
        localStorage.removeItem('app-language');
      }
    } catch {}

    // Default to the STUDIO'S OWN language, not German. This returned 'de'
    // unconditionally ("always default to German for new users"), so a studio in
    // Leeds or Lisbon served its visitors German no matter what locale it had
    // configured. SITE.lang comes from the tenant's identity; German remains the
    // default only for studios that actually configured German.
    const studioLang = (SITE.lang || '').slice(0, 2).toLowerCase() as Language;
    return SUPPORTED_LANGS.includes(studioLang) ? studioLang : 'en';
  });

  // Setter that records an explicit user choice. `persist` is false for
  // URL-driven syncing (an /en/ page forcing English) so it doesn't masquerade
  // as a manual preference that would then leak onto German URLs.
  const setLanguage = (lang: Language, persist: boolean = true) => {
    _setLanguage(lang);
    if (!persist) return;
    try {
      localStorage.setItem('language', lang);
      localStorage.setItem('languageUserSet', 'true');
    } catch {}
  };

  useEffect(() => {
    // Update HTML lang attribute
    try { document.documentElement.lang = language; } catch {}
  }, [language]);

  // Published "Manual Website Update" content (Settings → Manual Website
  // Update saves to /api/manual-pages). Without this overlay, admin edits were
  // stored in the DB but the live site kept rendering the built-in copy.
  const [manualOverrides, setManualOverrides] = useState<Record<string, string>>({});
  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const res = await fetch(`/api/manual-pages/published/all?language=${language}`);
        if (!res.ok) return;
        const data = await res.json();
        if (!cancelled && data && typeof data.content === 'object' && data.content) {
          setManualOverrides(data.content as Record<string, string>);
        }
      } catch { /* offline/prerender — built-in copy is the fallback */ }
    })();
    return () => { cancelled = true; };
  }, [language]);

  // Enabled languages + the studio's default (from /api/i18n/settings). English and
  // German ship built-in; French/Spanish are AI-generated and cached server-side.
  const [enabledLanguages, setEnabledLanguages] = useState<Language[]>(['en', 'de']);
  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const res = await fetch('/api/i18n/settings');
        if (!res.ok) return;
        const data = await res.json();
        if (cancelled) return;
        if (Array.isArray(data.enabledLanguages) && data.enabledLanguages.length) {
          setEnabledLanguages(data.enabledLanguages.filter((l: string) => (SUPPORTED_LANGS as string[]).includes(l)));
        }
        // Apply the studio default only if the user hasn't explicitly chosen a language.
        const userSet = (() => { try { return localStorage.getItem('languageUserSet'); } catch { return null; } })();
        if (userSet !== 'true' && data.defaultLanguage && (SUPPORTED_LANGS as string[]).includes(data.defaultLanguage)) {
          _setLanguage(data.defaultLanguage);
        }
      } catch { /* keep en/de defaults */ }
    })();
    return () => { cancelled = true; };
  }, []);

  // Runtime translation map for AI-generated languages (fr/es). Empty for en/de.
  const [runtimeTx, setRuntimeTx] = useState<Record<string, string>>({});
  useEffect(() => {
    let cancelled = false;
    if (language === 'en' || language === 'de') { setRuntimeTx({}); return; }
    (async () => {
      try {
        const res = await fetch(`/api/i18n/${language}`);
        if (!res.ok) return;
        const data = await res.json();
        if (!cancelled && data && typeof data === 'object') setRuntimeTx(data as Record<string, string>);
      } catch { /* fall back to English per key */ }
    })();
    return () => { cancelled = true; };
  }, [language]);

  const t = (key: string): string => {
    // Published admin edits win, then AI translation (fr/es), then the built-in
    // language string, then English, then the key itself.
    const override = manualOverrides[key];
    if (typeof override === 'string' && override.trim()) return override;
    const runtime = runtimeTx[key];
    if (typeof runtime === 'string' && runtime.trim()) return runtime;
    // An EMPTY string is a deliberate value, not a miss. Several keys default to ''
    // on purpose — the studio's address, its reviews, its milestone figures — because
    // the alternative was shipping another studio's. A truthiness check treated those
    // as missing and fell through to returning the KEY, so pages rendered literal
    // text like "contact.studioAddress". Only an absent key falls back.
    const current = (translations[language] as any)?.[key];
    if (typeof current === 'string') return current;
    const fallbackEn = (translations.en as any)[key];
    if (typeof fallbackEn === 'string') return fallbackEn;
    return key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, enabledLanguages }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
